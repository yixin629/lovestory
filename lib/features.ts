export const navigationFeatures = featureRegistry.filter((feature) => feature.showInNavigation)

export const homeFeatures = featureRegistry.filter((feature) => feature.showOnHome)

export const quickAccessFeatures = featureRegistry
  .filter((feature) => feature.quickAccessOrder !== undefined)
  .sort((a, b) => (a.quickAccessOrder ?? 0) - (b.quickAccessOrder ?? 0))

export const mobileNavigationFeatures = featureRegistry
  .filter((feature) => feature.mobileNavOrder !== undefined)
  .sort((a, b) => (a.mobileNavOrder ?? 0) - (b.mobileNavOrder ?? 0))

export function isFeaturePathActive(feature: FeatureDefinition, pathname: string) {
  if (feature.path === '/') return pathname === '/'

  return pathname === feature.path || pathname.startsWith(`${feature.path}/`)
}
